/**
 * Field guide to the world's survey and data programmes, rendered by
 * src/pages/edu/sources.astro (/edu/sources/). Educational: it lists the
 * programmes BullDozer uses AND the ones it does not, with the reason.
 *
 * Rules for maintaining this file:
 * - Every fact (coverage, countries, first year, frequency, access, licence)
 *   was read on the programme's own website or official documentation on
 *   2026-10-12; the pages read are in `sourceUrl`. Numbers that could not be
 *   read there are left out (e.g. "Worldwide" instead of a country count).
 * - For programmes BullDozer uses, the text must agree with src/data/sources.ts
 *   and src/data/licences.ts. `match` uses the same substrings as sources.ts so
 *   the page can count live datasets from meta.source; `licenceId` is the
 *   anchor on /licences/.
 * - "Live" counts and section links are computed at build time, never typed.
 */

export type Access = 'open download' | 'free account' | 'application/approval' | 'paid / licensed' | 'reports only';

export type GuideType =
  | 'cross-national attitude survey'
  | 'household & health survey'
  | 'panel study'
  | 'census microdata'
  | 'business survey'
  | 'national social survey'
  | 'education assessment'
  | 'index'
  | 'commercial poll';

export type SectionId = 'cross-national' | 'barometers' | 'household' | 'panels' | 'education' | 'indices' | 'statistics' | 'commercial';

export type InBullDozer =
  | {
      used: true;
      /** Substrings matched against dataset meta.source (same as sources.ts `match`). */
      match: string[];
      /** Slug prefixes of our datasets from this programme. */
      prefixes: string[];
      licenceId?: string;
      note?: string;
    }
  | { used: false; reason: string; licenceId?: string };

export interface GuideEntry {
  id: string;
  name: string;
  acronym?: string;
  producer: string;
  type: GuideType;
  section: SectionId;
  /** Regions; country counts and first year only where read on the official site. */
  coverage: string;
  frequency?: string;
  topics: string;
  /** Omitted when the programme's own pages could not be read on this point. */
  access?: Access;
  /** One line on the data terms, as the programme states them. */
  licence: string;
  url: string;
  /** Pages the facts above were read from. */
  sourceUrl: string[];
  inBullDozer: InBullDozer;
}

