/**
 * Licence, citation and disclaimer for every data source BullDozer publishes.
 * Rendered by src/pages/licences.astro and linked from each dataset page
 * (src/components/Provenance.astro) via licenceForSource(meta.source).
 *
 * Rules for maintaining this file:
 * - Every statement comes from the source's own terms page, read on the date in
 *   `checked`; the pages read are listed in `urls`. Do not paraphrase a
 *   `disclaimer` — it is the exact text the source requires us to show.
 * - `citation` is the citation format the source asks for, copied as given
 *   (placeholders such as [Year] are the source's own).
 * - `review` is an internal note for the maintainer (possible conflict between
 *   the terms and how BullDozer uses the data). It is NOT rendered.
 * - Entries are matched in array order: the first entry whose `match` text
 *   appears in a dataset's meta.source wins, so specific entries (EPI, Fraser,
 *   GPI via QoG; TI, Maddison, PISA via OWID) come before the general ones.
 */
export interface Licence {
  /** Anchor id on /licences/. */
  id: string;
  name: string;
  /** Substrings matched against dataset meta.source. Empty for non-dataset sources (maps, logos). */
  match: string[];
  /** Main terms-of-use / licence page. */
  termsUrl: string;
  licence: string;
  citation: string;
  /** Verbatim text the source requires to appear with the data. */
  disclaimer?: string;
  note?: string;
  /** What the source is used for, when it is not (only) datasets. */
  usedFor?: string;
  /** Every page the terms above were read from. */
  urls: string[];
  checked: string;
  /** Internal: possible conflict with our use, with the exact clause. Not rendered. */
  review?: string;
}

